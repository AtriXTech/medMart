                        order or an item becomes unavailable, the relevant pharmacy is
                        responsible for resolving the issue and ensuring the applicable
                        refund is initiated.
                    </p>

                    <p>
                        Although a required refund should be initiated promptly, the
                        time it takes for the refunded amount to appear in a customer's
