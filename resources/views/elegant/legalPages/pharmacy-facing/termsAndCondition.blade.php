                    <h2>8. Orders and Fulfillment</h2>

                    <p>
                        Customer orders submitted through MedMart are delivered to
                        the relevant pharmacy's order-management system for processing.
                    </p>

                    <p>
                        The pharmacy is responsible for reviewing and processing
                        orders received through the platform.
                    </p>

                    <p>
                        The pharmacy is responsible for accurately updating order
                        statuses and providing customers with appropriate information
                        regarding order readiness and pickup.
                    </p>

                    <p>
                        If a pharmacy cannot fulfill a paid order, it must cancel
                        the order and provide a full refund of the amount paid,
                        subject to the applicable refund process.
                    </p>

                    <p>
                        Where only part of an order is unavailable, the pharmacy
                        should communicate with the customer and refund the amount
                        attributable to the unavailable item where applicable.
                    </p>

                    <p>
                        Pharmacies must not falsely mark orders as ready, completed,
                        or fulfilled when the relevant order has not actually reached
                        that stage.
