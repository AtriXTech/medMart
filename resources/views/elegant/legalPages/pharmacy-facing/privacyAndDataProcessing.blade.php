                <!-- Introduction -->
                <section id="introduction">

                    <h2>1. Introduction</h2>

                    <p>
                        These Pharmacy Privacy & Data Processing Terms govern the
                        handling of customer information by pharmacies using the
                        MedMart platform.
                    </p>

                    <p>
                        MedMart provides technology that allows pharmacies to establish
                        and manage digital relationships with their customers.
                    </p>

                    <p>
                        Because pharmacies may access information relating to their
                        own customers through MedMart, pharmacies are responsible for
                        handling that information appropriately and in accordance
                        with applicable data-protection requirements.
                    </p>

                    <p>
                        These Terms should be read together with the
                        <a href="/pharmacy-terms">
                            Pharmacy Terms & Conditions
                        </a>
                        and MedMart's customer-facing
                        <a href="/privacy-policy">
                            Privacy Policy
                        </a>.
                    </p>

                </section>


                <!-- Roles -->
                <section id="roles">

                    <h2>2. Data Protection Roles</h2>

                    <p>
                        The specific legal role of MedMart and a participating pharmacy
                        may depend on the nature of the processing activity involved.
                    </p>

                    <p>
                        Depending on the activity, MedMart may process information
                        on behalf of a pharmacy, act as a controller for information
                        necessary to operate MedMart itself, or have another role
                        recognized under applicable data-protection law.
                    </p>

                    <p>
                        A pharmacy may independently determine certain purposes and
                        means for processing customer information in connection with
                        its own pharmacy operations.
                    </p>

                    <p>
                        Nothing in these Terms is intended to prevent either party
                        from having responsibilities imposed directly by applicable
                        data-protection law.
                    </p>

                </section>


                <!-- Data -->
                <section id="data">

                    <h2>3. Customer Data</h2>

                    <p>
                        Depending on the functionality used, customer information
                        accessible through a pharmacy's MedMart account may include
                        information such as:
                    </p>

                    <ul>
                        <li>Customer name.</li>
                        <li>Username or unique customer identifier.</li>
                        <li>Email address.</li>
                        <li>Phone number.</li>
                        <li>Address where the customer has manually provided one.</li>
                        <li>Orders associated with the pharmacy.</li>
                        <li>Products ordered and quantities.</li>
                        <li>Order prices and totals.</li>
                        <li>Payment and order status information.</li>
                        <li>Order dates and relevant fulfillment information.</li>
                        <li>Cancellation or refund information associated with orders.</li>
                    </ul>

                    <p>
                        The information available to a pharmacy is limited by the
                        functionality and access permissions provided to that pharmacy
                        through MedMart.
                    </p>

                </section>


                <!-- Access -->
                <section id="access">

                    <h2>4. Pharmacy Access to Customer Data</h2>

                    <p>
                        A pharmacy may access customer and order information associated
                        with customers who have joined or otherwise established a
                        relationship with that pharmacy through MedMart.
                    </p>

                    <p>
                        The pharmacy must use this access only for legitimate purposes
                        connected to its relationship with the customer and its
                        operation of the pharmacy.
                    </p>

                    <p>
                        A pharmacy does not have general access to customers or orders
                        belonging exclusively to another pharmacy.
                    </p>

                    <div class="mt-6 rounded-2xl border border-[#DBEBFB] bg-[#E9F3FE]/60 p-5 sm:p-6">

                        <div class="flex items-start gap-4">

                            <div class="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-white">
