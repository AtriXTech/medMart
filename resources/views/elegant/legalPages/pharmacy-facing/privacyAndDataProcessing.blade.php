                <section id="changes">

                    <h2>16. Changes to These Terms</h2>

                    <p>
                        MedMart may update these Pharmacy Privacy & Data Processing
                        Terms when its services, technology, data practices, or
                        applicable legal requirements change.
                    </p>

                    <p>
                        The "Last Updated" date at the beginning of this document
                        will be updated when changes are made.
                    </p>

                    <p>
                        Where required, MedMart may provide additional notice of
                        material changes.
                    </p>

