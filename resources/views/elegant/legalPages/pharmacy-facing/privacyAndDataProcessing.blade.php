                                <p class="!mb-0">
                                    MedMart is designed so that a pharmacy's access
                                    to customer information is limited to the
                                    pharmacy's own customer relationship and
                                    authorized data.
                                </p>

                            </div>

                        </div>

                    </div>

                </section>


                <!-- Purpose -->
                <section id="purpose">

                    <h2>5. Permitted Use of Customer Information</h2>

                    <p>
                        Pharmacies may use customer information accessed through
                        MedMart for legitimate purposes related to their pharmacy
                        operations.
                    </p>

                    <p>Examples include:</p>

                    <ul>
                        <li>Processing customer orders.</li>
                        <li>Preparing orders for pickup.</li>
                        <li>Communicating with customers about orders.</li>
                        <li>Confirming order details.</li>
                        <li>Resolving product or availability issues.</li>
                        <li>Processing applicable refunds or cancellations.</li>
                        <li>Maintaining appropriate pharmacy records.</li>
                        <li>Providing customer service relating to the pharmacy's operations.</li>
                    </ul>

                    <p>
                        Pharmacies must not use customer information obtained through
                        MedMart for unrelated or unauthorized purposes.
                    </p>

                </section>


                <!-- Tenant -->
                <section id="tenant">

                    <h2>6. Tenant Isolation and Access Controls</h2>

                    <p>
                        MedMart uses a multi-tenant architecture in which pharmacy
                        data is logically separated from the data of other pharmacies.
                    </p>

                    <p>
                        Pharmacy users are expected to access only the information
                        available to their authorized pharmacy account.
                    </p>

                    <p>
                        A pharmacy must not attempt to bypass application controls,
                        manipulate identifiers, exploit vulnerabilities, or otherwise
                        obtain access to another pharmacy's customer information.
                    </p>

                    <p>
                        Any suspected cross-pharmacy data exposure or unauthorized
                        access must be reported to MedMart promptly.
                    </p>

                </section>


                <!-- Security -->
                <section id="security">

                    <h2>7. Security Responsibilities</h2>

                    <p>
                        Pharmacies must implement reasonable measures to protect
                        customer information accessible through their MedMart account.
                    </p>

                    <p>This includes:</p>

                    <ul>
                        <li>Keeping account credentials secure.</li>
                        <li>Restricting staff access to authorized personnel.</li>
                        <li>Removing access when staff no longer require it.</li>
                        <li>Not sharing customer information unnecessarily.</li>
                        <li>Protecting devices used to access the pharmacy dashboard.</li>
                        <li>Reporting suspected security incidents promptly.</li>
                    </ul>

                    <p>
                        MedMart also maintains technical and organizational controls
                        intended to protect the platform and the information processed
                        through it.
                    </p>

                </section>


                <!-- Staff -->
                <section id="staff">

                    <h2>8. Staff and Authorized Users</h2>

                    <p>
                        Pharmacy administrators are responsible for ensuring that
                        staff members who receive access to MedMart understand their
                        responsibilities when handling customer information.
                    </p>

                    <p>
                        Staff should only access information necessary for their
                        assigned responsibilities.
                    </p>

                    <p>
                        A pharmacy should promptly restrict or remove access when
                        a staff member leaves the pharmacy, changes roles, or no
                        longer requires access.
                    </p>

                    <p>
                        Pharmacies should not permit unauthorized individuals to
                        operate their MedMart accounts.
                    </p>

                </section>


                <!-- Incidents -->
                <section id="incidents">

                    <h2>9. Security Incidents and Data Breaches</h2>

                    <p>
                        A pharmacy must notify MedMart promptly when it becomes aware
                        of unauthorized access, accidental disclosure, loss, misuse,
                        or another security incident involving customer information
                        processed through MedMart.
                    </p>

                    <p>
                        MedMart may investigate, contain, remediate, and take other
                        appropriate steps in response to a security incident.
                    </p>

                    <p>
                        Where notification to a regulator or affected individuals
                        is required by applicable law, the relevant party will take
                        the required steps within the applicable legal framework.
                    </p>

                    <p>
                        Pharmacies must reasonably cooperate with MedMart when
                        information is required to investigate or address an incident.
                    </p>

                </section>


                <!-- Third Party -->
                <section id="third-party">

                    <h2>10. Third-Party Service Providers</h2>

                    <p>
                        MedMart may use third-party service providers to operate
                        infrastructure and provide services necessary for the
                        platform.
                    </p>

                    <p>
                        These may include hosting, payment processing, email,
                        infrastructure, security, and other technology providers.
                    </p>

                    <p>
                        Third-party providers may process information only to the
                        extent necessary to provide their services to MedMart or
                        otherwise as permitted by applicable law and contractual
                        arrangements.
                    </p>

                    <p>
                        MedMart may process or store information outside Nigeria
                        where necessary to operate the platform, subject to
                        applicable data-protection requirements.
                    </p>

                </section>


                <!-- Retention -->
                <section id="retention">

                    <h2>11. Data Retention</h2>

                    <p>
                        Customer information may be retained for as long as reasonably
                        necessary for the purposes for which it was collected or
                        processed, including account administration, order records,
                        financial records, security, dispute resolution, legal
                        obligations, and other legitimate operational purposes.
                    </p>

                    <p>
                        MedMart does not currently promise a single fixed retention
                        period for all categories of information.
                    </p>

                    <p>
                        Pharmacies are responsible for considering their own legal
                        and regulatory retention obligations when maintaining copies
                        or records of customer information outside MedMart.
                    </p>

                </section>


                <!-- Customer Requests -->
                <section id="customer-requests">

                    <h2>12. Customer Privacy Requests</h2>

                    <p>
                        Customers may have rights under applicable data-protection
                        law regarding their personal information.
                    </p>

                    <p>
                        Where a request concerns information or processing carried
                        out directly by a pharmacy, the pharmacy may need to respond
                        to the customer in accordance with its legal responsibilities.
                    </p>

                    <p>
                        Where a request concerns MedMart's own processing activities,
                        MedMart may handle the request through its privacy process.
                    </p>

                    <p>
                        Pharmacies should cooperate with MedMart where customer
                        requests require information or action from both parties.
                    </p>

                    <p>
                        Privacy-related requests to MedMart can be directed to
                        <a href="mailto:privacy@medmart.com">
                            privacy@medmart.com
                        </a>.
                    </p>

                </section>


                <!-- Compliance -->
                <section id="compliance">

                    <h2>13. Data Protection Compliance</h2>

                    <p>
                        Pharmacies are responsible for complying with data-protection
                        requirements applicable to their own processing of customer
                        information.
                    </p>

                    <p>
                        This includes applicable requirements under the
                        <strong>Nigeria Data Protection Act 2023</strong> and
                        relevant guidance or requirements issued by the appropriate
                        Nigerian data-protection authorities.
                    </p>

                    <p>
                        Pharmacies should ensure that they have an appropriate legal
                        basis for processing customer information and that customers
                        receive any notices required by applicable law.
                    </p>

                    <p>
                        Nothing in these Terms transfers a pharmacy's independent
                        legal responsibilities to MedMart where the pharmacy is
                        independently responsible for a particular processing activity.
                    </p>

                </section>


                <!-- Confidentiality -->
                <section id="confidentiality">

                    <h2>14. Confidentiality</h2>

                    <p>
                        Customer information accessed through MedMart should be
                        treated as confidential and handled only by persons who
                        have a legitimate need to access it.
                    </p>

                    <p>
                        Pharmacies must not disclose customer information to
                        unauthorized third parties except where disclosure is
                        authorized by the customer, required for a legitimate
                        pharmacy purpose, required by law, or otherwise permitted
                        under applicable data-protection requirements.
                    </p>

                </section>


                <!-- MedMart Access -->
                <section id="medmart-access">

                    <h2>15. MedMart Access to Pharmacy Data</h2>

                    <p>
                        MedMart personnel are not intended to have unrestricted
                        access to all pharmacy customer information.
                    </p>

                    <p>
                        Controlled access may occur where reasonably necessary for
                        purposes such as platform security, maintenance, technical
                        support, troubleshooting, fraud prevention, compliance,
                        incident investigation, or other legitimate operational
                        purposes.
                    </p>

                    <p>
                        Such access should be limited to the information and scope
                        reasonably necessary for the relevant purpose and subject
                        to applicable access controls.
                    </p>

                </section>


