                <p>
                    Features and plan limits may vary between plans. A
                    pharmacy should review the information displayed for its
                    selected plan before completing payment.
                </p>


                <!-- 3 -->
                <h2 id="pricing">3. Pricing & Billing</h2>

                <p>
                    Subscription fees are charged according to the billing
                    cycle associated with the selected plan.
                </p>

                <p>
                    Unless otherwise stated, a monthly subscription is billed
                    for each monthly subscription period. The applicable
                    amount is displayed before the pharmacy confirms payment.
                </p>

                <p>
                    The pharmacy is responsible for ensuring that its billing
                    information and payment method remain valid and available
                    for subscription payments.
                </p>

                <p>
                    MedMart may update subscription pricing from time to time.
                    Where a price change affects a future billing period,
                    MedMart may provide notice or display the updated price
                    before the new amount becomes applicable, subject to
                    applicable law.
                </p>


                <!-- 4 -->
                <h2 id="payment">4. Payment Authorization</h2>

                <p>
                    MedMart currently uses <strong>Paystack</strong> to process
                    pharmacy subscription payments.
                </p>

                <p>
                    By subscribing to a recurring plan, the pharmacy
                    authorizes the applicable payment process to charge the
                    selected payment method for the subscription according to
                    the applicable billing cycle.
                </p>

                <p>
                    Payment processing may be subject to Paystack's own terms,
                    privacy practices, security controls, and processing
                    requirements.
                </p>

                <p>
                    MedMart does not intentionally store full payment card
                    numbers, card PINs, CVVs, or bank credentials. MedMart may
                    retain payment references and subscription records needed
                    to identify transactions, reconcile payments, manage
                    subscriptions, and provide support.
                </p>


                <!-- 5 -->
                <h2 id="activation">5. Subscription Activation & Renewal</h2>

                <p>
                    A subscription becomes active after the required payment
                    has been successfully processed and MedMart has received
                    the applicable payment confirmation.
                </p>

                <p>
                    A successful subscription payment may establish a current
                    billing period for the pharmacy. The subscription record
                    may contain the start and end dates of that period.
                </p>

                <p>
                    Where recurring billing is enabled, the subscription may
                    renew automatically at the end of the current billing
                    period using the authorized payment method.
                </p>

                <p>
                    Renewal depends on successful payment processing and the
                    subscription remaining eligible for renewal.
                </p>

                <p>
                    MedMart may provide renewal or billing reminders through
                    available account or notification channels where
                    applicable.
                </p>


                <!-- 6 -->
                <h2 id="failed-payments">6. Failed Payments</h2>

                <p>
                    A subscription payment may fail for reasons including an
                    expired payment method, insufficient funds, payment
                    provider issues, bank restrictions, or other processing
                    failures.
                </p>

                <p>
                    When a subscription payment is unsuccessful, the pharmacy
                    may not receive or retain active subscription status for
                    that billing period until the payment issue is resolved.
                </p>

                <p>
                    Depending on the subscription state, MedMart may mark the
                    subscription as <strong>past_due</strong>,
                    <strong>inactive</strong>, or another applicable status.
                </p>

                <p>
                    MedMart may restrict subscription-dependent features or
                    access when required payment remains unresolved. Any
                    applicable grace period or additional payment window will
                    depend on MedMart's then-current billing rules.
                </p>

                <p>
                    A failed subscription payment does not create a customer
                    order refund because pharmacy subscriptions and customer
                    orders are separate transactions.
                </p>


                <!-- 7 -->
                <h2 id="cancellation">7. Subscription Cancellation</h2>

                <p>
                    A pharmacy may request cancellation of its subscription
                    through the available subscription controls or by
                    contacting MedMart where self-service cancellation is not
                    available.
                </p>

                <p>
                    Cancelling a recurring subscription is intended to stop
                    future subscription renewals and future recurring charges.
                </p>

                <p>
                    Cancellation does not automatically create a refund for a
                    billing period that has already started unless MedMart
                    expressly provides otherwise or a refund is required by
                    applicable law.
                </p>

                <p>
                    Where a subscription remains active until the end of a
                    paid billing period, the pharmacy may continue to access
                    subscription features during that period, subject to
                    these terms and any applicable plan conditions.
                </p>


                <!-- 8 -->
                <h2 id="refunds">8. Subscription Refunds</h2>

                <p>
                    Subscription fees are generally charged for access to the
                    applicable subscription period and are not automatically
                    refundable simply because a pharmacy stops using MedMart
                    before the end of that period.
                </p>

                <p>
                    A refund may be considered where:
                </p>

                <ul>
                    <li>
                        a duplicate subscription payment was processed;
                    </li>

                    <li>
                        a billing error caused an incorrect charge;
                    </li>

                    <li>
                        MedMart approves a refund under its applicable
                        customer-service or billing rules; or
                    </li>

                    <li>
                        a refund is required by applicable law.
                    </li>
                </ul>

                <p>
                    Where MedMart approves a refund, the refund will normally
                    be initiated through the applicable payment provider or
                    payment method used for the original transaction.
                </p>

                <p>
                    The time required for the refunded amount to appear in the
                    pharmacy's account may depend on the payment provider,
                    bank, card network, or other financial institution.
                </p>


                <!-- 9 -->
                <h2 id="plan-changes">9. Plan Changes</h2>

                <p>
                    MedMart may allow a pharmacy to change from one
                    subscription plan to another where multiple plans are
                    available.
                </p>

                <p>
                    The pricing and billing consequences of a plan change,
                    including any difference in price or timing of the
                    change, will be displayed to the pharmacy where applicable
                    before the change is confirmed.
                </p>

                <p>
                    MedMart may also introduce, modify, discontinue, or replace
                    subscription plans or features, subject to applicable
                    notice and legal requirements.
                </p>


                <!-- 10 -->
                <h2 id="fees">10. Taxes, Charges & Additional Fees</h2>

                <p>
                    The subscription price displayed to the pharmacy is the
                    amount applicable to the selected plan at the time of
                    purchase, subject to any applicable taxes, charges, or
                    fees that are separately disclosed or required by law.
                </p>

                <p>
                    Payment providers, banks, card networks, or other financial
                    institutions may impose their own charges. Such charges
                    may be outside MedMart's control.
                </p>

                <p>
                    Where MedMart is required to collect or account for taxes
                    or other government charges, the applicable amount may be
                    included in the payment amount or otherwise disclosed to
                    the pharmacy.
                </p>


                <!-- 11 -->
                <h2 id="suspension">11. Suspension, Expiry & Reactivation</h2>

                <p>
                    A subscription may become inactive, cancelled, expired,
                    or otherwise restricted when its applicable billing period
                    ends without successful renewal or when the pharmacy's
                    account is suspended or terminated.
                </p>

                <p>
                    MedMart may restrict access to subscription-dependent
                    features where a pharmacy has an unpaid subscription
                    balance or no active subscription.
                </p>

                <p>
                    A pharmacy may be able to reactivate its subscription by
                    completing the required payment and meeting the applicable
                    account requirements.
                </p>

                <p>
                    Subscription status may include states such as
                    <strong>active</strong>, <strong>past_due</strong>,
                    <strong>inactive</strong>, or <strong>cancelled</strong>.
                </p>


                <!-- 12 -->
                <h2 id="disputes">12. Payment Disputes & Chargebacks</h2>

                <p>
                    If a pharmacy believes that it has been charged incorrectly,
                    it should contact MedMart as soon as reasonably possible
                    with the relevant transaction or subscription information.
                </p>

                <p>
                    MedMart may review payment records, subscription records,
                    payment references, and related information to investigate
                    a billing dispute.
                </p>

                <p>
                    Where a payment provider or financial institution is
                    involved, the resolution may also be subject to that
                    provider's dispute, reversal, chargeback, or transaction
                    procedures.
                </p>

                <p>
                    A pharmacy should not provide passwords, PINs, CVVs, or
                    other sensitive authentication information when reporting
                    a billing issue.
                </p>


