                <h2 id="introduction">1. Introduction</h2>

                <p>
                    These Pharmacy Subscription & Billing Terms govern the
                    purchase and use of paid MedMart subscription plans by
                    pharmacies and pharmacy operators.
                </p>

                <p>
                    MedMart is a technology platform that provides pharmacies
                    with tools for managing customer orders, inventory,
                    pharmacy operations, and related digital workflows.
                    A subscription gives the pharmacy access to the features
                    and services included in the applicable plan.
                </p>

                <p>
                    These terms apply to the pharmacy account that purchases
                    the subscription and do not create a subscription
                    relationship between MedMart and the pharmacy's customers.
                </p>


                <!-- 2 -->
                <h2 id="subscription-plan">2. Subscription Plan</h2>

                <p>
                    MedMart may offer different subscription plans with
                    different features, limits, pricing, or billing periods.
                    The plan available to a pharmacy is the plan selected
                    during subscription or subsequently changed through the
                    pharmacy's account.
                </p>

                <div class="my-6 rounded-2xl border border-[#B1D0FB] bg-[#E9F3FE] p-5 sm:p-6">

                    <div class="flex items-start gap-4">

